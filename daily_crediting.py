"""Daily crediting engine for CEDARS EMPIRE.

Credits only approved, evidence-backed activities. No guaranteed investment returns,
deposit-based yield, or unverified Grid revenue is generated by this service.
A scheduler should invoke process_daily_credits() from a durable job runner.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP
from zoneinfo import ZoneInfo
import json
import uuid


SCHEMAS = [
    """CREATE TABLE IF NOT EXISTS earning_rules (
        id TEXT PRIMARY KEY, rule_name TEXT NOT NULL UNIQUE, activity_type TEXT NOT NULL,
        rate TEXT NOT NULL, reward_type TEXT NOT NULL, enabled INTEGER NOT NULL DEFAULT 0,
        requires_verified_funding INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS earning_activities (
        id TEXT PRIMARY KEY, user_email TEXT NOT NULL, activity_type TEXT NOT NULL,
        qualifying_volume TEXT NOT NULL, currency TEXT NOT NULL DEFAULT 'USDT',
        evidence_ref TEXT, status TEXT NOT NULL DEFAULT 'PENDING',
        funding_verified INTEGER NOT NULL DEFAULT 0, risk_score INTEGER NOT NULL DEFAULT 0,
        activity_at TEXT NOT NULL, reviewed_by TEXT, reviewed_at TEXT, created_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS wallets (
        user_email TEXT PRIMARY KEY, available_balance TEXT NOT NULL DEFAULT '0',
        lifetime_earnings TEXT NOT NULL DEFAULT '0', updated_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS daily_credit_runs (
        id TEXT PRIMARY KEY, processing_date TEXT NOT NULL UNIQUE, status TEXT NOT NULL,
        started_at TEXT NOT NULL, completed_at TEXT, processed_count INTEGER NOT NULL DEFAULT 0,
        total_amount TEXT NOT NULL DEFAULT '0', notes TEXT
    )""",
    """CREATE TABLE IF NOT EXISTS transactions (
        id TEXT PRIMARY KEY, user_email TEXT NOT NULL, transaction_type TEXT NOT NULL,
        amount TEXT NOT NULL, currency TEXT NOT NULL, reference TEXT NOT NULL UNIQUE,
        status TEXT NOT NULL, activity_id TEXT, created_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS ledger_entries (
        id TEXT PRIMARY KEY, user_email TEXT NOT NULL, transaction_id TEXT NOT NULL,
        entry_type TEXT NOT NULL, amount TEXT NOT NULL, currency TEXT NOT NULL,
        created_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS fraud_flags (
        id TEXT PRIMARY KEY, user_email TEXT NOT NULL, risk_score INTEGER NOT NULL,
        reason TEXT NOT NULL, reviewed INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS audit_logs (
        id TEXT PRIMARY KEY, user_email TEXT, action TEXT NOT NULL, details TEXT NOT NULL,
        created_at TEXT NOT NULL
    )""",
]


def initialize(db_connect):
    conn, kind = db_connect()
    try:
        cur = conn.cursor()
        for statement in SCHEMAS:
            cur.execute(statement)
        conn.commit()
    finally:
        conn.close()


def business_date(timezone_name: str = "Pacific/Auckland", now=None) -> str:
    """Return the current local business date; IANA zone rules handle DST."""
    current = now or datetime.now(timezone.utc)
    if current.tzinfo is None:
        current = current.replace(tzinfo=timezone.utc)
    return current.astimezone(ZoneInfo(timezone_name)).date().isoformat()


def previous_business_window(timezone_name: str = "Pacific/Auckland", now=None):
    current = now or datetime.now(timezone.utc)
    if current.tzinfo is None:
        current = current.replace(tzinfo=timezone.utc)
    local_now = current.astimezone(ZoneInfo(timezone_name))
    previous_day = local_now.date() - timedelta(days=1)
    start = datetime.combine(previous_day, datetime.min.time(), ZoneInfo(timezone_name))
    end = datetime.combine(local_now.date(), datetime.min.time(), ZoneInfo(timezone_name))
    return start.astimezone(timezone.utc), end.astimezone(timezone.utc)


def _decimal(value) -> Decimal:
    try:
        amount = Decimal(str(value))
    except (InvalidOperation, TypeError, ValueError):
        raise ValueError("Credit amount must be numeric.")
    if not amount.is_finite() or amount <= 0:
        raise ValueError("Credit amount must be a finite positive value.")
    return amount.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def process_daily_credits(db_connect, timezone_name="Pacific/Auckland", now=None, risk_limit=70):
    """Atomically credit each eligible activity once; intended for a durable scheduler."""
    process_date = business_date(timezone_name, now)
    started = datetime.now(timezone.utc).isoformat()
    conn, kind = db_connect()
    placeholder = "%s" if kind == "postgres" else "?"
    def q(sql):
        return sql.replace("?", placeholder)
    cur = conn.cursor()
    processed = 0
    total = Decimal("0.00")
    try:
        # One run per business date. A unique DB constraint is the final concurrency guard.
        cur.execute(q("INSERT INTO daily_credit_runs (id,processing_date,status,started_at) VALUES (?,?,?,?) ON CONFLICT(processing_date) DO NOTHING"),
                    (str(uuid.uuid4()), process_date, "RUNNING", started))
        conn.commit()
        cur.execute(q("SELECT status FROM daily_credit_runs WHERE processing_date=?"), (process_date,))
        row = cur.fetchone()
        if not row or (row["status"] if isinstance(row, dict) else row[0]) == "COMPLETED":
            return {"status": "ALREADY_PROCESSED", "date": process_date, "count": 0, "amount": "0.00"}
        start, end = previous_business_window(timezone_name, now)
        cur.execute(q("""SELECT id,user_email,activity_type,qualifying_volume,currency,evidence_ref,
                        risk_score,funding_verified FROM earning_activities
                        WHERE status='APPROVED' AND activity_at >= ? AND activity_at < ?
                        ORDER BY activity_at,id"""), (start.isoformat(), end.isoformat()))
        activities = cur.fetchall()
        conn.commit()
        for raw in activities:
            activity = dict(raw) if not isinstance(raw, dict) else raw
            cur.execute(q("SELECT rate,enabled,requires_verified_funding,reward_type FROM earning_rules WHERE activity_type=?"),
                        (activity["activity_type"],))
            rule_raw = cur.fetchone()
            if not rule_raw:
                conn.commit()
                continue
            rule = dict(rule_raw) if not isinstance(rule_raw, dict) else rule_raw
            conn.commit()
            if not int(rule["enabled"]):
                conn.commit()
                continue
            if int(rule["requires_verified_funding"]) and not int(activity["funding_verified"]):
                conn.commit()
                continue
            if int(activity["risk_score"] or 0) >= risk_limit:
                cur.execute(q("INSERT INTO fraud_flags (id,user_email,risk_score,reason,created_at) VALUES (?,?,?,?,?)"),
                            (str(uuid.uuid4()), activity["user_email"], int(activity["risk_score"]),
                             "Activity exceeded configured risk threshold; credit held for review", started))
                conn.commit()
                continue
            try:
                amount = _decimal(Decimal(str(activity["qualifying_volume"])) * Decimal(str(rule["rate"])))
            except Exception:
                continue
            if amount <= 0:
                continue
            reference = f"ACTIVITY-{activity['id']}-{process_date}"
            cur.execute("BEGIN")
            try:
                # Unique reference prevents duplicate credit even if workers race or retry.
                cur.execute(q("INSERT INTO transactions (id,user_email,transaction_type,amount,currency,reference,status,activity_id,created_at) VALUES (?,?,?,?,?,?,?,?,?) ON CONFLICT(reference) DO NOTHING"),
                            (str(uuid.uuid4()), activity["user_email"], rule["reward_type"], str(amount),
                             activity["currency"], reference, "COMPLETED", activity["id"], started))
                if cur.rowcount == 0:
                    conn.rollback()
                    continue
                cur.execute(q("SELECT available_balance,lifetime_earnings FROM wallets WHERE user_email=?"),
                            (activity["user_email"],))
                wr = cur.fetchone()
                old_balance = Decimal(str((wr["available_balance"] if isinstance(wr, dict) else wr[0]) if wr else "0"))
                old_lifetime = Decimal(str((wr["lifetime_earnings"] if isinstance(wr, dict) else wr[1]) if wr else "0"))
                new_balance = old_balance + amount
                cur.execute(q("INSERT INTO wallets (user_email,available_balance,lifetime_earnings,updated_at) VALUES (?,?,?,?) ON CONFLICT(user_email) DO UPDATE SET available_balance=excluded.available_balance,lifetime_earnings=excluded.lifetime_earnings,updated_at=excluded.updated_at"),
                            (activity["user_email"], str(new_balance), str(old_lifetime + amount), started))
                cur.execute(q("SELECT id FROM transactions WHERE reference=?"), (reference,))
                tr = cur.fetchone()
                transaction_id = tr["id"] if isinstance(tr, dict) else tr[0]
                cur.execute(q("INSERT INTO ledger_entries (id,user_email,transaction_id,entry_type,amount,currency,created_at) VALUES (?,?,?,?,?,?,?)"),
                            (str(uuid.uuid4()), activity["user_email"], transaction_id, "CREDIT", str(amount), activity["currency"], started))
                cur.execute(q("INSERT INTO audit_logs (id,user_email,action,details,created_at) VALUES (?,?,?,?,?)"),
                            (str(uuid.uuid4()), activity["user_email"], "daily_credit_issued",
                             json.dumps({"reference": reference, "amount": str(amount), "activity_id": activity["id"]}), started))
                conn.commit()
                processed += 1
                total += amount
            except Exception:
                conn.rollback()
                raise
        cur.execute(q("UPDATE daily_credit_runs SET status=?,completed_at=?,processed_count=?,total_amount=? WHERE processing_date=?"),
                    ("COMPLETED", datetime.now(timezone.utc).isoformat(), processed, str(total), process_date))
        conn.commit()
        return {"status": "COMPLETED", "date": process_date, "count": processed, "amount": str(total)}
    except Exception:
        conn.rollback()
        try:
            cur.execute(q("UPDATE daily_credit_runs SET status=? WHERE processing_date=?"), ("FAILED", process_date))
            conn.commit()
        except Exception:
            conn.rollback()
        raise
    finally:
        cur.close()
        conn.close()
